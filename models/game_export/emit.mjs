// Write the compressed GLBs / icons as base64 ES modules into the game source (text files: bundled
// into the single-file build and pushable to GitHub as plain text).
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const DST = process.env.DST || fileURLToPath(new URL('../../src/assets', import.meta.url));   // models/game_export → src/assets
mkdirSync(DST, { recursive: true });
const head = (what) => `// ${what} — generated by tools (Blender → gltf-transform → base64). Do not edit by hand.\n`;
for (const f of process.argv.slice(2)) {
  const name = f.split('/').pop();
  const b = readFileSync(f).toString('base64');
  writeFileSync(`${DST}/${name}.js`, head(name) + `export default '${b}';\n`);
  console.log(name, (b.length / 1024).toFixed(0), 'KB b64');
}
if (process.env.ICONS) {
  const d = process.env.ICONS, out = {};
  for (const n of readdirSync(d).sort()) if (n.endsWith('.webp')) out[n.replace('.webp', '')] = 'data:image/webp;base64,' + readFileSync(`${d}/${n}`).toString('base64');
  writeFileSync(`${DST}/cropIcons.js`, head('seed-packet crop icon decals (256², WebP)') + 'export default ' + JSON.stringify(out, null, 1) + ';\n');
  console.log('cropIcons.js', Object.keys(out).join(','));
}
