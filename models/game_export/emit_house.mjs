// Write the compressed house GLB into the game source as base64 parts (each under 1 M characters,
// like the farmer) plus src/assets/house.js that joins them.   usage: node emit_house.mjs out/house.glb
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const DST = fileURLToPath(new URL('../../src/assets', import.meta.url));
const src = process.argv[2] || 'out/house.glb';
const b = readFileSync(src).toString('base64');
const PART = 900000;
const n = Math.ceil(b.length / PART);
for (const f of readdirSync(DST)) if (/^house\.glb\.\d+\.js$/.test(f)) unlinkSync(`${DST}/${f}`);
const head = (what) => `// ${what} — generated by tools (Blender → gltf-transform → base64). Do not edit by hand.\n`;
const names = [];
for (let i = 0; i < n; i++) {
  writeFileSync(`${DST}/house.glb.${i}.js`, head(`house.glb part ${i + 1}/${n}`) + `export default '${b.slice(i * PART, (i + 1) * PART)}';\n`);
  names.push(`P${i}`);
}
writeFileSync(`${DST}/house.js`, '// The timber house (GLB, base64 split into parts). See models/source/house in the repo.\n' +
  names.map((p, i) => `import ${p} from './house.glb.${i}.js';`).join('\n') + `\nexport default ${names.join(' + ')};\n`);
console.log('house.glb', (b.length / 1024).toFixed(0), 'KB b64 in', n, 'parts');
