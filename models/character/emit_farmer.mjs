// Write the packed farmer GLB into the game source as base64 ES modules, split into parts
// (< 900 KB each, so every file stays small enough for plain-text tooling / GitHub API pushes).
//   node emit_farmer.mjs out/farmer.glb ../farm/src/assets
import { readFileSync, writeFileSync, readdirSync, unlinkSync } from 'node:fs';
const [src = 'out/farmer.glb', dst = '/data/farm/src/assets'] = process.argv.slice(2);
const b = readFileSync(src).toString('base64');
const PART = 880 * 1024, n = Math.ceil(b.length / PART);
for (const f of readdirSync(dst)) if (/^farmer\.glb\.\d+\.js$/.test(f)) unlinkSync(`${dst}/${f}`);
for (let i = 0; i < n; i++) {
  const s = b.slice(i * PART, (i + 1) * PART);
  writeFileSync(`${dst}/farmer.glb.${i}.js`, `// farmer.glb part ${i + 1}/${n} — generated by models/character/emit_farmer.mjs (MakeHuman CC0 base → Blender → gltf-transform → base64). Do not edit by hand.\nexport default '${s}';\n`);
  console.log(`farmer.glb.${i}.js`, (s.length / 1024).toFixed(0), 'KB');
}
writeFileSync(`${dst}/farmer.js`, `// The farmer character (skinned GLB, base64 split into parts). See models/character in the repo.\n` +
  Array.from({ length: n }, (_, i) => `import P${i} from './farmer.glb.${i}.js';`).join('\n') + `\nexport default ${Array.from({ length: n }, (_, i) => 'P' + i).join(' + ')};\n`);
console.log('farmer.js parts', n, 'total', (b.length / 1024).toFixed(0), 'KB b64');
